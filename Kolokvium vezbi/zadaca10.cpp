/*Од стандарден влез се читаат непознат број на хексадецимални цифри се додека не се внесе точка (.). 
Ваша задача е да го пресметате декадниот збир на внесените хексадецимални цифри. 
Доколку добиениот декаден збир е делив со 16 се печати Pogodok. Доколку истиот тој збир покрај што е делив со 16 плус завршува на 16 
(последните цифри му се 1 и 6), се печати Poln pogodok инаку се печати самиот збир.

Пример:

влез: A 7 F 2 0 c A 5

излез: 61

(61 = 10 + 7 + 15 + 2 + 0 + 12 + 10 + 5, бројот не е делив со 16, ниту пак последните цифри му се 1,6)*/

#include <iostream>

using namespace std;

int main(){
    char c;

    int sum = 0;

    while(cin>>c && c!='.'){
        if(c>='0' && c<='9'){
            sum += c-'0';
        }else if(c>='A' && c<='F'){
            sum += c- 'A' + 10;
        }else if(c>='a' && c<='f'){
            sum += c - 'a' + 10;
        }
    }
    if(sum%16==0 && sum%100==16){
        cout<<"Poln pogodok"<<endl;
        return 0;
    }else if(sum%16==0){
        cout<<"Pogodok"<<endl;
        return 0;
    }else{
        cout<<sum<<endl;
    }

    return 0;
}