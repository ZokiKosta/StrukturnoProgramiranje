/*
Да се напише програма коа од тастатура чита два цели броа К и N. Потоа од тастатура се внесуваат уште N парови природни броеви
S и R, каде 5>9 a R<=9.
За секо од внесените парови, броот S да се трансформира така што:
• ако цифрата R се сретнува во него парен бро пати, тогаш првите две цифри од броот (неговата назначана
цифра и наредната цифра до неа) ce додаваат како нови две цифри на краот од броот, пр. 1223 и 2 →
122312);
• ако цифрата R се сретнува во него непарен бро пати, тогаш на краот од
"средината на броот" (тоа што
останува од броот кога ке се тргнат назначаната и намалку значаната
цифра) ке се залепи сумата на назначаната и намалку значарната
цифра од броот (пр. 12345 и 2 →
2346; 98887 и 8 → 88816);
• ако цифрата R НЕ се сретнува ниту еднаш, броот S не се менува.
Доколку вака трансформираниот бро е
делив со к, на екранот да се испечати DA, а NE во спротивно (за секо бро во посебен ред).
Трансформирането на броот S да се реши со функциа/функции за добиване максимален бро поени.
Пример со обаснуванье:
2565 (R ce сретнува парен бро пати) →
S = 256525, делив е со К=5, излезот е
DA
98887 (R ce сретнува непарен бро пати) → S = 88816, не е делив со К=5, излезот e NE
23 (R не се сретнува во S) → S = 23, не е делив со К=5, излезот е NEбро поени.
*/
#include <iostream>

using namespace std;

int stepen(int n, int m){
    if(m==0){
        return 1;
    }
    return n * stepen(n,m-1);
}

int transformacija(int s, int pati, int brcif){
    if(pati==0){
        return s;
    }
    else if(pati%2==0){
        int prviteDve = s / stepen(10, brcif-2);

        return s * 100 + prviteDve;
    }
    else{
        int prva = s / stepen(10, brcif-1);
        int posledna = s % 10;

        int sredina = (s % stepen(10, brcif-1)) / 10;

        return sredina * 10 + prva + posledna;
    }
}

int main(){
    int k,n;
    cin>>k>>n;

    int s,r;

    for(int i=0; i<n; i++){
        cin>>s>>r;

        int pati=0;
        int temp=s;
        int brcif=0;

        while(temp>0){
            if(temp%10==r){
                pati++;
            }
            temp/=10;
            brcif++;
        }

        s=transformacija(s,pati,brcif);

        if(s%k==0){
            cout<<"DA"<<endl;
        }
        else{
            cout<<"NE"<<endl;
        }
    }

    return 0;
}
